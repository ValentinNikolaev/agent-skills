#!/usr/bin/env python3
"""Generate complete Claude and Codex skill wrappers from canonical skills.

The canonical source tree defaults to::

    agent-plugins/skills/<skill-name>/

For every selected source skill, this script generates complete, self-contained
copies under::

    claude/skills/<skill-name>/
    codex/skills/<skill-name>/

The generated SKILL.md keeps the source YAML frontmatter and full body, but adds
an explicit generated-file notice immediately after the frontmatter. All bundled
resources are copied as regular files, including references/, scripts/, assets/,
and README files. No symlinks are created.

Typical usage::

    python scripts/generate_skill_wrappers.py
    python scripts/generate_skill_wrappers.py code-review stop-slop
    python scripts/generate_skill_wrappers.py --check
    python scripts/generate_skill_wrappers.py --clean

Exit codes:
    0  Success; in --check mode all generated files are current.
    1  Validation, generation, or drift-check failure.
    2  Invalid command-line arguments (argparse).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from typing import Iterable, Iterator, Sequence

GENERATOR_VERSION = "1.0.0"
GENERATED_MARKER = "<!-- GENERATED BY generate_skill_wrappers.py; DO NOT EDIT MANUALLY. -->"
README_MARKER = "<!-- GENERATED BY generate_skill_wrappers.py; DO NOT EDIT MANUALLY. -->"
IGNORED_NAMES = {".DS_Store", "Thumbs.db", "__pycache__"}
IGNORED_SUFFIXES = {".pyc", ".pyo"}

# Conservative matcher for ordinary Markdown links and images. It intentionally
# ignores inline code and raw prose paths; its job is to catch common broken
# references without trying to implement a full Markdown parser.
MARKDOWN_LINK_RE = re.compile(r"!?\[[^\]]*\]\(([^)]+)\)")
TOP_LEVEL_NAME_RE = re.compile(r"(?m)^name\s*:\s*(.+?)\s*$")
TOP_LEVEL_DESCRIPTION_RE = re.compile(r"(?m)^description\s*:\s*(.+?)\s*$")


class GenerationError(RuntimeError):
    """Raised for a user-actionable generation failure."""


@dataclass(frozen=True)
class PlatformTarget:
    key: str
    label: str
    root: Path


@dataclass(frozen=True)
class SourceSkill:
    name: str
    directory: Path
    skill_file: Path
    frontmatter: str
    body: str
    declared_name: str | None
    description: str | None


@dataclass(frozen=True)
class TreeSnapshot:
    files: dict[str, str]


