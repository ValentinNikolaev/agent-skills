def update_readme(repo_root: Path, skills: Sequence[SourceSkill], *, check: bool, dry_run: bool) -> bool:
    readme_path = repo_root / "README.md"
    expected = render_repo_readme(repo_root, skills)
    current = ""
    if readme_path.is_file():
        current = readme_path.read_text(encoding="utf-8-sig")
    if current == expected:
        return False
    if check:
        print("OUTDATED README.md", file=sys.stderr)
        return True
    if not dry_run:
        readme_path.write_text(expected, encoding="utf-8", newline="\n")
    return True


def parse_semver(version: str, manifest_path: Path) -> tuple[int, int, int]:
    match = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", version)
    if not match:
        raise GenerationError(
            f"Cannot bump non-semver version {version!r} in {manifest_path}. "
            "Expected MAJOR.MINOR.PATCH."
        )
    return tuple(int(part) for part in match.groups())


def bump_version(version: str, bump: str, manifest_path: Path) -> str:
    major, minor, _patch = parse_semver(version, manifest_path)
    if bump == "major":
        return f"{major + 1}.0.0"
    if bump == "minor":
        return f"{major}.{minor + 1}.0"
    raise GenerationError(f"Unsupported version bump type {bump!r}")


def bump_plugin_manifest(repo_root: Path, platform: PlatformTarget, bump: str) -> str:
    manifest_path = repo_root / f".{platform.key}-plugin" / "plugin.json"
    if not manifest_path.is_file():
        raise GenerationError(
            f"Cannot bump {platform.key} plugin version; manifest is missing: "
            f"{manifest_path}"
        )

    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8-sig"))
    except json.JSONDecodeError as exc:
        raise GenerationError(f"Invalid JSON in {manifest_path}: {exc}") from exc

    current_version = manifest.get("version")
    if not isinstance(current_version, str):
        raise GenerationError(f"Missing string version in {manifest_path}")

    next_version = bump_version(current_version, bump, manifest_path)
    manifest["version"] = next_version
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return next_version


def run(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    repo_root = args.repo_root.resolve()
    source_root = resolve_under_repo(repo_root, args.source_dir)
    platforms = selected_platforms(args, repo_root)
    platform_snapshots_before = {
        platform.key: snapshot_tree(platform.root) for platform in platforms
    }

    try:
        skills = discover_skills(source_root, args.skills)
        all_source_names = {
            path.name
            for path in source_root.iterdir()
            if path.is_dir() and (path / "SKILL.md").is_file()
        }

        validation_warnings: list[str] = []
        for skill in skills:
            validate_no_symlinks(skill)
            if skill.declared_name and skill.declared_name != skill.name:
                validation_warnings.append(
                    f"{skill.name}: frontmatter name {skill.declared_name!r} does not "
                    f"match directory name {skill.name!r}"
                )
            validation_warnings.extend(validate_local_links(skill))

        if validation_warnings:
            heading = "ERROR" if args.strict_links else "WARNING"
            for warning in validation_warnings:
                print(f"{heading}: {warning}", file=sys.stderr)
            if args.strict_links:
                raise GenerationError("Source skill validation failed")

        drift_count = 0
        changed_count = 0

        with tempfile.TemporaryDirectory(prefix="skill-wrappers-") as temporary:
            temporary_root = Path(temporary)

            for skill in skills:
                for platform in platforms:
                    expected = temporary_root / platform.key / skill.name
                    write_generated_tree(
                        source=skill,
                        platform=platform,
                        source_root=source_root,
                        repo_root=repo_root,
                        destination=expected,
                    )
                    target = platform.root / skill.name
                    differences = compare_trees(expected, target)

                    if args.check:
                        if differences:
                            drift_count += 1
                            print(
                                f"OUTDATED {platform.key}: {display_path(target, repo_root)}",
                                file=sys.stderr,
                            )
                            for difference in differences:
                                print(f"  - {difference}", file=sys.stderr)
                        elif not args.quiet:
                            print(f"OK {platform.key}: {display_path(target, repo_root)}")
                        continue

                    if not differences:
                        if not args.quiet:
                            print(f"UNCHANGED {platform.key}: {display_path(target, repo_root)}")
                        continue

                    changed_count += 1
                    if args.dry_run:
                        print(f"WOULD UPDATE {platform.key}: {display_path(target, repo_root)}")
                        for difference in differences:
                            print(f"  - {difference}")
                    else:
                        replace_directory(expected, target, args.force)
                        if not args.quiet:
                            print(f"UPDATED {platform.key}: {display_path(target, repo_root)}")

        stale_count = 0
        if args.clean:
            stale_count = remove_stale_generated_skills(
                all_source_names,
                platforms,
                check=args.check,
                dry_run=args.dry_run,
                quiet=args.quiet,
            )

        readme_changed = update_readme(
            repo_root,
            skills,
            check=args.check,
            dry_run=args.dry_run,
        )

        if args.check:
            total_drift = drift_count + stale_count + int(readme_changed)
            if total_drift:
                print(
                    f"Generated skills are out of date: {drift_count} changed/missing, "
                    f"{stale_count} stale, {int(readme_changed)} README.",
                    file=sys.stderr,
                )
                return 1
            print(f"Generated skills are current ({len(skills)} source skill(s)).")
            return 0

        version_bumps: list[str] = []
        if not args.dry_run:
            for platform in platforms:
                before = platform_snapshots_before[platform.key]
                after = snapshot_tree(platform.root)
                bump = compare_snapshots(before, after)
                if not bump:
                    continue
                next_version = bump_plugin_manifest(repo_root, platform, bump)
                version_bumps.append(f"{platform.key} {bump} -> {next_version}")

        verb = "would be updated" if args.dry_run else "updated"
        stale_verb = "would be removed" if args.dry_run else "removed"
        readme_verb = "would be updated" if args.dry_run else "updated"
        summary = (
            f"Done: {changed_count} target skill(s) {verb}; "
            f"{stale_count} stale target skill(s) {stale_verb}; "
            f"README {'unchanged' if not readme_changed else readme_verb}."
        )
        if version_bumps:
            summary += " Version bumps: " + "; ".join(version_bumps) + "."
        print(summary)
        return 0

    except GenerationError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1
    except OSError as exc:
        print(f"ERROR: filesystem operation failed: {exc}", file=sys.stderr)
        return 1


def main() -> None:
    raise SystemExit(run())


if __name__ == "__main__":
    main()
